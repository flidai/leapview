import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { icons } from 'lucide'

type IconNode = (typeof icons)[keyof typeof icons]

const root = resolve(import.meta.dir, '..')
const iconDir = resolve(root, 'node_modules/lucide/dist/esm/icons')

const pascal = (name: string) => name.split('-').map((part) => part ? part[0]!.toUpperCase() + part.slice(1) : '').join('')
const kebab = (name: string) => name
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
  .toLowerCase()

export interface LucideCatalogData {
  canonicalNames: string[]
  aliases: Record<string, string[]>
  nodes: Record<string, IconNode>
}

export interface LucideCatalogSources extends LucideCatalogData {
  catalogSource: string
  nodesSource: string
  goSource: string
}

export function generateLucideCatalogData(
  iconDirectory = iconDir,
  iconExports: typeof icons = icons,
): LucideCatalogData {
  const canonicalNames = readdirSync(iconDirectory)
    .filter((name) => name.endsWith('.mjs'))
    .map((name) => name.slice(0, -4))
    .sort()

  const canonicalByNode = new Map<IconNode, string>()
  const nodes: Record<string, IconNode> = {}
  for (const name of canonicalNames) {
    const node = iconExports[pascal(name) as keyof typeof iconExports] as IconNode | undefined
    if (!node) throw new Error(`Lucide canonical icon ${name} has no ${pascal(name)} export`)
    canonicalByNode.set(node, name)
    nodes[name] = node
  }

  const aliases = new Map<string, string[]>()
  for (const [exportName, node] of Object.entries(iconExports)) {
    const canonical = canonicalByNode.get(node as IconNode)
    if (!canonical) continue
    const alias = kebab(exportName)
    if (alias === canonical) continue
    const values = aliases.get(canonical) ?? []
    values.push(alias)
    aliases.set(canonical, values)
  }

  return {
    canonicalNames,
    aliases: Object.fromEntries(canonicalNames
      .filter((name) => aliases.has(name))
      .map((name) => [name, [...new Set(aliases.get(name)!)].sort()])),
    nodes,
  }
}

export function generateLucideCatalogSources(data = generateLucideCatalogData()): LucideCatalogSources {
  const { canonicalNames, aliases, nodes } = data
  const header = '// Code generated by scripts/generate_lucide_icon_catalog.ts. DO NOT EDIT.\n'
  const catalogSource = header +
    `export const canonicalLucideIconNames = ${JSON.stringify(canonicalNames)} as const\n` +
    `export const lucideIconAliases: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(aliases, null, 2)}\n` +
    `export { lucideIconNodes } from './lucide-icon-nodes'\n`
  const nodesSource = header +
    `import type { IconNode } from 'lucide'\n` +
    `export const lucideIconNodes = ${JSON.stringify(nodes)} as unknown as Readonly<Record<string, IconNode>>\n`
  const goNames = canonicalNames.map((name) => `\t${JSON.stringify(name)}: {},`).join('\n')
  const goSource = `${header}package appearance\n\nvar validIcons = map[string]struct{}{\n${goNames}\n}\n\nfunc ValidIcon(name string) bool { _, ok := validIcons[name]; return ok }\n`
  return { ...data, catalogSource, nodesSource, goSource }
}

function writeGeneratedCatalog(): void {
  const { catalogSource, nodesSource, goSource } = generateLucideCatalogSources()
  writeFileSync(resolve(root, 'web/generated/lucide-icon-catalog.ts'), catalogSource)
  writeFileSync(resolve(root, 'web/generated/lucide-icon-nodes.ts'), nodesSource)

  const goPath = resolve(root, 'internal/dashboard/appearance/icons_gen.go')
  writeFileSync(goPath, goSource)
  execFileSync('gofmt', ['-w', goPath])
}

if (import.meta.main) writeGeneratedCatalog()
