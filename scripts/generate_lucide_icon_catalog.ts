import { readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { icons } from 'lucide'

type IconNode = (typeof icons)[keyof typeof icons]

const root = resolve(import.meta.dir, '..')
const iconDir = resolve(root, 'node_modules/lucide/dist/esm/icons')
const canonicalNames = readdirSync(iconDir)
  .filter((name) => name.endsWith('.mjs'))
  .map((name) => name.slice(0, -4))
  .sort()

const pascal = (name: string) => name.split('-').map((part) => part ? part[0]!.toUpperCase() + part.slice(1) : '').join('')
const kebab = (name: string) => name
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
  .toLowerCase()

const canonicalByNode = new Map<IconNode, string>()
for (const name of canonicalNames) {
  const node = icons[pascal(name) as keyof typeof icons]
  if (!node) throw new Error(`Lucide canonical icon ${name} has no ${pascal(name)} export`)
  canonicalByNode.set(node, name)
}

const aliases = new Map<string, string[]>()
for (const [exportName, node] of Object.entries(icons)) {
  const canonical = canonicalByNode.get(node)
  if (!canonical) continue
  const alias = kebab(exportName)
  if (alias === canonical) continue
  const values = aliases.get(canonical) ?? []
  values.push(alias)
  aliases.set(canonical, values)
}

const ts = `// Code generated by scripts/generate_lucide_icon_catalog.ts. DO NOT EDIT.\n` +
  `import type { IconNode } from 'lucide'\n` +
  `export const canonicalLucideIconNames = ${JSON.stringify(canonicalNames)} as const\n` +
  `export const lucideIconAliases: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(Object.fromEntries([...aliases].map(([key, values]) => [key, values.sort()])), null, 2)}\n` +
  `export const lucideIconNodes = ${JSON.stringify(Object.fromEntries(canonicalNames.map((name) => [name, icons[pascal(name) as keyof typeof icons]])))} as unknown as Readonly<Record<string, IconNode>>\n`
writeFileSync(resolve(root, 'web/generated/lucide-icon-catalog.ts'), ts)

const goNames = canonicalNames.map((name) => `\t${JSON.stringify(name)}: {},`).join('\n')
const go = `// Code generated by scripts/generate_lucide_icon_catalog.ts. DO NOT EDIT.\npackage appearance\n\nvar validIcons = map[string]struct{}{\n${goNames}\n}\n\nfunc ValidIcon(name string) bool { _, ok := validIcons[name]; return ok }\n`
writeFileSync(resolve(root, 'internal/dashboard/appearance/icons_gen.go'), go)
