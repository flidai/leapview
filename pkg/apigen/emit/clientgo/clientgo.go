// Package clientgo emits typed Go API clients from APIGen IR.
package clientgo

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/Yacobolo/toolbelt/apigen/emit/gotype"
	"github.com/Yacobolo/toolbelt/apigen/ir"
)

// Options configures Go client emission.
type Options struct {
	PackageName string
}

// Emit renders typed client contracts over APIGen's generic transport.
func Emit(doc ir.Document, opts Options) ([]byte, error) {
	if err := ir.Validate(doc); err != nil {
		return nil, fmt.Errorf("validate ir document: %w", err)
	}
	normalized := doc
	if err := ir.Normalize(&normalized); err != nil {
		return nil, fmt.Errorf("normalize ir document: %w", err)
	}
	return emit(normalized, opts)
}

func emit(doc ir.Document, opts Options) ([]byte, error) {
	endpoints := append([]ir.Endpoint(nil), doc.Endpoints...)
	sort.Slice(endpoints, func(left, right int) bool {
		return endpoints[left].OperationID < endpoints[right].OperationID
	})
	if err := validateOperationNames(endpoints); err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by apigen typed client emitter. DO NOT EDIT.\n")
	b.WriteString("package " + packageName(opts) + "\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	if hasGeneratedFailures(endpoints) {
		b.WriteString("\t\"errors\"\n")
	}
	b.WriteString("\t\"net/http\"\n")
	b.WriteString("\t\"net/url\"\n\n")
	b.WriteString("\tapigenclient \"github.com/Yacobolo/toolbelt/apigen/runtime/client\"\n")
	b.WriteString(")\n\n")

	b.WriteString("// GenClient executes API operations through an injected generic transport.\n")
	b.WriteString("type GenClient struct {\n\ttransport apigenclient.Transport\n}\n\n")
	b.WriteString("// NewGenClient constructs a typed generated client.\n")
	b.WriteString("func NewGenClient(transport apigenclient.Transport) *GenClient {\n")
	b.WriteString("\treturn &GenClient{transport: transport}\n")
	b.WriteString("}\n\n")

	if len(endpoints) > 0 {
		b.WriteString("const (\n")
		for _, endpoint := range endpoints {
			b.WriteString("\tGenOperation" + exportedName(endpoint.OperationID) + " = " + strconv.Quote(endpoint.OperationID) + "\n")
		}
		b.WriteString(")\n\n")
	}

	for _, endpoint := range endpoints {
		if err := emitOperation(&b, doc, endpoint); err != nil {
			return nil, fmt.Errorf("operation %q: %w", endpoint.OperationID, err)
		}
	}
	return []byte(b.String()), nil
}

func validateOperationNames(endpoints []ir.Endpoint) error {
	seen := make(map[string]string, len(endpoints))
	for _, endpoint := range endpoints {
		name := "Gen" + exportedName(endpoint.OperationID)
		if previous, exists := seen[name]; exists {
			return fmt.Errorf("operation IDs %q and %q both generate %s", previous, endpoint.OperationID, name)
		}
		seen[name] = endpoint.OperationID
	}
	return nil
}

func emitOperation(b *strings.Builder, doc ir.Document, endpoint ir.Endpoint) error {
	name := exportedName(endpoint.OperationID)
	pathParams := parametersIn(endpoint, "path")
	queryParams := parametersIn(endpoint, "query")
	headerParams := parametersIn(endpoint, "header")

	if len(queryParams) > 0 {
		b.WriteString("// Gen" + name + "ClientParams is the typed query contract for " + name + ".\n")
		b.WriteString("type Gen" + name + "ClientParams struct {\n")
		emitParameterFields(b, queryParams)
		b.WriteString("}\n\n")
	}
	if len(headerParams) > 0 {
		b.WriteString("// Gen" + name + "ClientHeaders is the typed header contract for " + name + ".\n")
		b.WriteString("type Gen" + name + "ClientHeaders struct {\n")
		emitParameterFields(b, headerParams)
		b.WriteString("}\n\n")
	}

	b.WriteString("// Gen" + name + "ClientRequest is the typed request contract for " + name + ".\n")
	b.WriteString("type Gen" + name + "ClientRequest struct {\n")
	emitParameterFields(b, pathParams)
	if len(queryParams) > 0 {
		b.WriteString("\tParams Gen" + name + "ClientParams\n")
	}
	if len(headerParams) > 0 {
		b.WriteString("\tHeaders Gen" + name + "ClientHeaders\n")
	}
	if endpoint.RequestBody != nil {
		bodyType, err := requestBodyType(endpoint)
		if err != nil {
			return err
		}
		if !endpoint.RequestBody.Required {
			bodyType = "*" + bodyType
		}
		b.WriteString("\tBody " + bodyType + "\n")
	}
	b.WriteString("}\n\n")

	responseBodyType, accept, hasBody, err := successResponseType(endpoint)
	if err != nil {
		return err
	}
	responseType := "Gen" + name + "ClientResponse"
	b.WriteString("// " + responseType + " is the typed successful response contract for " + name + ".\n")
	b.WriteString("type " + responseType + " struct {\n")
	if hasBody {
		b.WriteString("\tBody " + responseBodyType + "\n")
	}
	b.WriteString("\tStatusCode int\n")
	b.WriteString("\tHeaders http.Header\n")
	b.WriteString("\tContentType string\n")
	b.WriteString("}\n\n")
	if endpoint.Command != nil && len(endpoint.Command.Failures) > 0 {
		emitOperationFailures(b, endpoint)
	}

	b.WriteString("// " + name + " executes the generated " + endpoint.OperationID + " operation.\n")
	b.WriteString("func (client *GenClient) " + name + "(ctx context.Context, request Gen" + name + "ClientRequest) (" + responseType + ", error) {\n")
	if hasBody {
		b.WriteString("\tvar body " + responseBodyType + "\n")
	}
	b.WriteString("\tquery := url.Values{}\n")
	for _, parameter := range queryParams {
		b.WriteString("\tapigenclient.AddQuery(query, " + strconv.Quote(parameter.Name) + ", request.Params." + exportedName(parameter.Name) + ", " + strconv.FormatBool(parameterExplodes(parameter)) + ")\n")
	}
	b.WriteString("\theaders := http.Header{}\n")
	for _, parameter := range headerParams {
		b.WriteString("\tapigenclient.AddHeader(headers, " + strconv.Quote(parameter.Name) + ", request.Headers." + exportedName(parameter.Name) + ")\n")
	}
	b.WriteString("\ttransportRequest := apigenclient.Request{\n")
	b.WriteString("\t\tOperationID: GenOperation" + name + ",\n")
	b.WriteString("\t\tMethod: " + strconv.Quote(strings.ToUpper(endpoint.Method)) + ",\n")
	b.WriteString("\t\tPath: " + strconv.Quote(ir.JoinAPIPath(doc.API.BasePath, endpoint.Path)) + ",\n")
	if len(pathParams) > 0 {
		b.WriteString("\t\tPathParams: map[string]string{")
		for index, parameter := range pathParams {
			if index > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(parameter.Name) + ": apigenclient.FormatValue(request." + exportedName(parameter.Name) + ")")
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t\tQuery: query,\n")
	b.WriteString("\t\tHeaders: headers,\n")
	if endpoint.RequestBody != nil {
		content, _ := ir.PrimaryRequestBodyContent(endpoint)
		b.WriteString("\t\tBody: request.Body,\n")
		b.WriteString("\t\tContentType: " + strconv.Quote(content.ContentType) + ",\n")
	}
	if accept != "" {
		b.WriteString("\t\tAccept: " + strconv.Quote(accept) + ",\n")
	}
	b.WriteString("\t}\n")
	if hasBody {
		b.WriteString("\tmetadata, err := client.transport.DoAPIGen(ctx, transportRequest, &body)\n")
	} else {
		b.WriteString("\tmetadata, err := client.transport.DoAPIGen(ctx, transportRequest, nil)\n")
	}
	b.WriteString("\tresponse := " + responseType + "{\n")
	if hasBody {
		b.WriteString("\t\tBody: body,\n")
	}
	b.WriteString("\t\tStatusCode: metadata.StatusCode,\n")
	b.WriteString("\t\tHeaders: metadata.Headers,\n")
	b.WriteString("\t\tContentType: metadata.ContentType,\n")
	b.WriteString("\t}\n")
	if endpoint.Command != nil && len(endpoint.Command.Failures) > 0 {
		b.WriteString("\tif err != nil { err = gen" + name + "FailureFromError(err) }\n")
	}
	b.WriteString("\treturn response, err\n")
	b.WriteString("}\n\n")
	return nil
}

func hasGeneratedFailures(endpoints []ir.Endpoint) bool {
	for _, endpoint := range endpoints {
		if endpoint.Command != nil && len(endpoint.Command.Failures) > 0 {
			return true
		}
	}
	return false
}

func emitOperationFailures(b *strings.Builder, endpoint ir.Endpoint) {
	name := exportedName(endpoint.OperationID)
	failureType := "Gen" + name + "Failure"
	implementationType := "gen" + name + "Failure"

	b.WriteString("// " + failureType + " is a sealed operation-owned failure declared by " + endpoint.OperationID + ".\n")
	b.WriteString("type " + failureType + " interface {\n")
	b.WriteString("\terror\n")
	b.WriteString("\tProblem() apigenclient.ProblemDetails\n")
	b.WriteString("\tgen" + name + "Failure()\n")
	b.WriteString("}\n\n")
	b.WriteString("type " + implementationType + " struct {\n")
	b.WriteString("\tkind string\n")
	b.WriteString("\tproblem *apigenclient.ProblemError\n")
	b.WriteString("}\n\n")
	b.WriteString("func (failure *" + implementationType + ") Error() string { return failure.problem.Error() }\n")
	b.WriteString("func (failure *" + implementationType + ") Unwrap() error { return failure.problem }\n")
	b.WriteString("func (failure *" + implementationType + ") Problem() apigenclient.ProblemDetails { return failure.problem.Problem }\n")
	b.WriteString("func (*" + implementationType + ") gen" + name + "Failure() {}\n\n")

	b.WriteString("// Match" + failureType + " requires one handler for every declared failure variant.\n")
	b.WriteString("func Match" + failureType + "[T any](failure " + failureType)
	for _, contract := range endpoint.Command.Failures {
		b.WriteString(", on" + exportedName(contract.Kind) + " func(apigenclient.ProblemDetails) T")
	}
	b.WriteString(") T {\n")
	b.WriteString("\ttyped := failure.(*" + implementationType + ")\n")
	b.WriteString("\tswitch typed.kind {\n")
	for _, contract := range endpoint.Command.Failures {
		b.WriteString("\tcase " + strconv.Quote(contract.Kind) + ":\n")
		b.WriteString("\t\treturn on" + exportedName(contract.Kind) + "(typed.Problem())\n")
	}
	b.WriteString("\tdefault:\n")
	b.WriteString("\t\tpanic(\"unreachable generated failure kind\")\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n\n")

	b.WriteString("func gen" + name + "FailureFromError(err error) error {\n")
	b.WriteString("\tvar problem *apigenclient.ProblemError\n")
	b.WriteString("\tif !errors.As(err, &problem) { return err }\n")
	b.WriteString("\tswitch problem.Problem.Code {\n")
	for _, contract := range endpoint.Command.Failures {
		b.WriteString("\tcase " + strconv.Quote(contract.Code) + ":\n")
		b.WriteString("\t\tif problem.Response.StatusCode != " + strconv.Itoa(contract.StatusCode) + " || (problem.Problem.Status != 0 && problem.Problem.Status != " + strconv.Itoa(contract.StatusCode) + ") {\n")
		b.WriteString("\t\t\treturn &apigenclient.UnexpectedProblemError{ProblemError: problem, Violation: \"declared failure status does not match its contract\"}\n")
		b.WriteString("\t\t}\n")
		b.WriteString("\t\treturn &" + implementationType + "{kind: " + strconv.Quote(contract.Kind) + ", problem: problem}\n")
	}
	b.WriteString("\tdefault:\n")
	b.WriteString("\t\treturn &apigenclient.UnexpectedProblemError{ProblemError: problem, Violation: \"problem code is not declared by this operation\"}\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n\n")
}

func emitParameterFields(b *strings.Builder, parameters []ir.Parameter) {
	for _, parameter := range parameters {
		fieldType := schemaRefType(parameter.Schema)
		if !parameter.Required {
			fieldType = "*" + fieldType
		}
		b.WriteString("\t" + exportedName(parameter.Name) + " " + fieldType + "\n")
	}
}

func requestBodyType(endpoint ir.Endpoint) (string, error) {
	content, ok := ir.PrimaryRequestBodyContent(endpoint)
	if !ok {
		return "", fmt.Errorf("request body requires content")
	}
	switch content.BodyKind {
	case "binary", "file":
		return "[]byte", nil
	case "text":
		return "string", nil
	case "json":
		if content.Schema == nil {
			return "", fmt.Errorf("JSON request body requires a schema")
		}
		return schemaRefType(*content.Schema), nil
	default:
		return "", fmt.Errorf("unsupported client request body kind %q", content.BodyKind)
	}
}

func successResponseType(endpoint ir.Endpoint) (typeName, accept string, hasBody bool, err error) {
	selectedType := ""
	selectedAccept := ""
	foundSuccess := false
	for _, response := range endpoint.Responses {
		if response.StatusCode < 200 || response.StatusCode >= 300 {
			continue
		}
		foundSuccess = true
		content, contentFound := preferredClientResponseContent(response)
		if !contentFound {
			if selectedType != "" {
				return "", "", false, fmt.Errorf("success responses mix body and bodyless shapes")
			}
			continue
		}
		currentType, typeErr := responseContentType(content)
		if typeErr != nil {
			return "", "", false, typeErr
		}
		if selectedType == "" {
			selectedType = currentType
			selectedAccept = content.ContentType
			continue
		}
		if selectedType != currentType {
			return "", "", false, fmt.Errorf("success responses have incompatible JSON body schemas")
		}
	}
	if !foundSuccess {
		return "", "", false, fmt.Errorf("requires a success response")
	}
	if selectedType == "" {
		return "", "", false, nil
	}
	return selectedType, selectedAccept, true, nil
}

func preferredClientResponseContent(response ir.Response) (ir.BodyContent, bool) {
	for _, content := range response.Contents {
		if content.BodyKind == "json" {
			return content, true
		}
	}
	return ir.PrimaryResponseContent(response)
}

func responseContentType(content ir.BodyContent) (string, error) {
	switch content.BodyKind {
	case "binary", "file":
		return "[]byte", nil
	case "text":
		return "string", nil
	case "json":
		if content.Schema == nil {
			return "", fmt.Errorf("JSON success response requires a schema")
		}
		return schemaRefType(*content.Schema), nil
	default:
		return "", fmt.Errorf("unsupported client response body kind %q", content.BodyKind)
	}
}

func schemaRefType(ref ir.SchemaRef) string {
	return gotype.Ref(ref, func(name string) string {
		return "GenSchema" + exportedName(name)
	})
}

func parametersIn(endpoint ir.Endpoint, location string) []ir.Parameter {
	var parameters []ir.Parameter
	for _, parameter := range endpoint.Parameters {
		if strings.EqualFold(parameter.In, location) {
			parameters = append(parameters, parameter)
		}
	}
	return parameters
}

func parameterExplodes(parameter ir.Parameter) bool {
	return parameter.Explode == nil || *parameter.Explode
}

func packageName(opts Options) string {
	if strings.TrimSpace(opts.PackageName) == "" {
		return "api"
	}
	return opts.PackageName
}

func exportedName(value string) string {
	parts := splitIdentifier(value)
	for index := range parts {
		if parts[index] == "" {
			continue
		}
		parts[index] = strings.ToUpper(parts[index][:1]) + parts[index][1:]
	}
	return strings.Join(parts, "")
}

func splitIdentifier(value string) []string {
	var parts []string
	start := 0
	for index, character := range value {
		if character == '-' || character == '_' || character == ' ' || character == '.' || character == '/' {
			if start < index {
				parts = append(parts, value[start:index])
			}
			start = index + 1
			continue
		}
		if index > start && character >= 'A' && character <= 'Z' {
			parts = append(parts, value[start:index])
			start = index
		}
	}
	if start < len(value) {
		parts = append(parts, value[start:])
	}
	return parts
}
