// Package modelts emits TypeScript data-contract model types from APIGen IR.
package modelts

import (
	"fmt"
	"sort"
	"strings"

	"github.com/Yacobolo/toolbelt/apigen/emit/contractimport"
	"github.com/Yacobolo/toolbelt/apigen/emit/contractutil"
	"github.com/Yacobolo/toolbelt/apigen/ir"
)

// Options configures TypeScript model emission.
type Options struct {
	ContractImports map[string]ContractImport
}

type ContractImport = contractimport.Binding

// Emit renders TypeScript data-contract model types for doc.Contracts.
func Emit(doc ir.Document, opts Options) ([]byte, error) {
	imports := contractimport.Bindings(opts.ContractImports)
	if err := imports.Validate(doc); err != nil {
		return nil, err
	}
	localNames, importedNames := contractutil.DependencyNamesPartition(doc, func(name string, _ ir.Schema) bool {
		_, _, ok := imports.Schema(doc, name)
		return ok
	})
	var b strings.Builder
	b.WriteString("// Code generated by apigen data-contract TypeScript emitter. DO NOT EDIT.\n\n")
	aliases := map[string]string{}
	for _, name := range importedNames {
		namespace, binding, _ := imports.Schema(doc, name)
		if binding.TypeScriptModule == "" {
			return nil, fmt.Errorf("external schema %q requires typescript_module", name)
		}
		aliases[namespace] = tsNamespaceAlias(namespace)
	}
	for _, namespace := range sortedKeys(aliases) {
		binding := imports[namespace]
		b.WriteString("import type * as ")
		b.WriteString(aliases[namespace])
		b.WriteString(" from ")
		b.WriteString(quotedTSString(binding.TypeScriptModule))
		b.WriteString("\n")
	}
	if len(aliases) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("export type JsonObject = Record<string, unknown>\n\n")
	resolveType := func(ref ir.SchemaRef) string { return tsType(doc, imports, aliases, ref) }
	for _, name := range localNames {
		schema, ok := doc.Schemas[name]
		if !ok {
			return nil, fmt.Errorf("contract schema %q is missing", name)
		}
		emitSchema(&b, name, schema, resolveType)
	}
	rootTypes := make([]string, 0, len(doc.Contracts))
	for _, contract := range doc.Contracts {
		if name, ok := ir.NormalizedSchemaRefName(contract.Schema); ok {
			if _, _, external := imports.Schema(doc, name); external {
				continue
			}
		}
		rootTypes = append(rootTypes, resolveType(contract.Schema))
	}
	sort.Strings(rootTypes)
	if len(rootTypes) > 0 {
		b.WriteString("export type DataContractEnvelope = ")
		b.WriteString(strings.Join(rootTypes, " | "))
		b.WriteString("\n")
	}
	return []byte(b.String()), nil
}

func emitSchema(b *strings.Builder, name string, schema ir.Schema, resolveType func(ir.SchemaRef) string) {
	switch schema.Type {
	case "union":
		variants := make([]string, 0, len(schema.OneOf))
		for _, variant := range schema.OneOf {
			variants = append(variants, resolveType(variant))
		}
		b.WriteString("export type ")
		b.WriteString(exportedName(name))
		b.WriteString(" = ")
		b.WriteString(strings.Join(variants, " | "))
		b.WriteString("\n\n")
	case "object", "":
		if schema.Base != nil {
			// TypeScript interfaces may only extend statically known object
			// types. A generated base can itself be a union (for example the
			// closed PathSourceLocation variants), so model inheritance is
			// emitted as an intersection alias. Base-less models remain
			// interfaces for declaration merging and the existing public shape.
			b.WriteString("export type ")
			b.WriteString(exportedName(name))
			b.WriteString(" = ")
			b.WriteString(resolveType(*schema.Base))
			b.WriteString(" & {\n")
		} else {
			b.WriteString("export interface ")
			b.WriteString(exportedName(name))
			b.WriteString(" {\n")
		}
		required := contractutil.RequiredSet(schema)
		for _, propertyName := range contractutil.OrderedProperties(schema) {
			property := schema.Properties[propertyName]
			optional := ""
			if _, ok := required[propertyName]; !ok {
				optional = "?"
			}
			b.WriteString("  ")
			b.WriteString(propertyName)
			b.WriteString(optional)
			b.WriteString(": ")
			b.WriteString(resolveType(property.Schema))
			b.WriteString("\n")
		}
		b.WriteString("}\n\n")
	case "array":
		itemType := "unknown"
		if schema.Items != nil {
			itemType = resolveType(*schema.Items)
		}
		b.WriteString("export type ")
		b.WriteString(exportedName(name))
		b.WriteString(" = ")
		b.WriteString(itemType)
		b.WriteString("[]\n\n")
	default:
		b.WriteString("export type ")
		b.WriteString(exportedName(name))
		b.WriteString(" = ")
		if len(schema.Enum) > 0 {
			values := make([]string, 0, len(schema.Enum))
			for _, value := range schema.Enum {
				values = append(values, quotedTSString(value))
			}
			b.WriteString(strings.Join(values, " | "))
		} else {
			b.WriteString(scalarTSType(schema.Type))
		}
		b.WriteString("\n\n")
	}
}

func tsType(doc ir.Document, imports contractimport.Bindings, aliases map[string]string, ref ir.SchemaRef) string {
	if ref.Ref != "" {
		name, ok := ir.NormalizedSchemaRefName(ref)
		if ok {
			if namespace, _, external := imports.Schema(doc, name); external {
				return aliases[namespace] + "." + exportedName(name)
			}
			return exportedName(name)
		}
		return "unknown"
	}
	if ref.AdditionalProperties != nil {
		if ref.AdditionalProperties.Schema != nil {
			return "Record<string, " + tsType(doc, imports, aliases, *ref.AdditionalProperties.Schema) + ">"
		}
		return "JsonObject"
	}
	switch ref.Type {
	case "boolean":
		return "boolean"
	case "integer", "number":
		return "number"
	case "array":
		itemType := "unknown"
		if ref.Items != nil {
			itemType = tsType(doc, imports, aliases, *ref.Items)
		}
		return itemType + "[]"
	case "object":
		return "JsonObject"
	case "string":
		if len(ref.Enum) > 0 {
			values := make([]string, 0, len(ref.Enum))
			for _, value := range ref.Enum {
				values = append(values, quotedTSString(value))
			}
			return strings.Join(values, " | ")
		}
		return "string"
	case "null":
		return "null"
	default:
		return "unknown"
	}
}

func tsNamespaceAlias(namespace string) string {
	return exportedName(strings.ReplaceAll(namespace, ".", "_"))
}

func sortedKeys(values map[string]string) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func scalarTSType(schemaType string) string {
	switch schemaType {
	case "boolean":
		return "boolean"
	case "integer", "number":
		return "number"
	case "string":
		return "string"
	default:
		return "unknown"
	}
}

func exportedName(value string) string {
	parts := strings.FieldsFunc(strings.TrimSpace(value), func(r rune) bool {
		return r == '-' || r == '_' || r == '.' || r == '/' || r == ' '
	})
	if len(parts) == 0 {
		return "Value"
	}
	for i := range parts {
		if parts[i] == "" {
			continue
		}
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

func quotedTSString(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "\\'") + "'"
}
