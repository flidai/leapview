// Package modelgo emits Go data-contract model types from APIGen IR.
package modelgo

import (
	"fmt"
	"sort"
	"strings"

	"github.com/Yacobolo/toolbelt/apigen/emit/contractimport"
	"github.com/Yacobolo/toolbelt/apigen/emit/contractutil"
	"github.com/Yacobolo/toolbelt/apigen/emit/gotype"
	"github.com/Yacobolo/toolbelt/apigen/emit/gounion"
	"github.com/Yacobolo/toolbelt/apigen/ir"
)

// Options configures Go model emission.
type Options struct {
	PackageName     string
	ContractImports map[string]ContractImport
}

type ContractImport = contractimport.Binding

// Emit renders Go data-contract model types for doc.Contracts.
func Emit(doc ir.Document, opts Options) ([]byte, error) {
	imports := contractimport.Bindings(opts.ContractImports)
	if err := imports.Validate(doc); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by apigen data-contract Go emitter. DO NOT EDIT.\n")
	b.WriteString("package ")
	b.WriteString(packageName(opts))
	b.WriteString("\n\n")

	names, imported := dependencyNames(doc, imports)
	goImports := map[string]string{}
	if hasUnion(doc, names) {
		goImports["bytes"] = ""
		goImports["encoding/json"] = ""
		goImports["fmt"] = ""
	}
	for _, name := range imported {
		_, binding, _ := imports.Schema(doc, name)
		if binding.GoPackage == "" {
			return nil, fmt.Errorf("external schema %q requires go_package", name)
		}
		goImports[binding.GoPackage] = binding.GoAlias
	}
	emitImports(&b, goImports)
	resolveName := func(name string) string {
		if _, binding, ok := imports.Schema(doc, name); ok {
			return binding.GoAlias + "." + exportedName(name)
		}
		return exportedName(name)
	}
	for _, name := range names {
		schema, ok := doc.Schemas[name]
		if !ok {
			return nil, fmt.Errorf("contract schema %q is missing", name)
		}
		emitSchema(&b, doc, name, schema, resolveName)
	}
	return []byte(b.String()), nil
}

func packageName(opts Options) string {
	if strings.TrimSpace(opts.PackageName) == "" {
		return "contracts"
	}
	return opts.PackageName
}

func emitSchema(b *strings.Builder, doc ir.Document, name string, schema ir.Schema, resolveName func(string) string) {
	typeName := exportedName(name)
	switch schema.Type {
	case "union":
		if schema.Discriminator == nil {
			if hasScalarObjectUnion(schema) {
				gounion.EmitScalarObject(b, doc, name, schema, resolveName)
			} else {
				b.WriteString("type " + typeName + " = any\n\n")
			}
		} else {
			gounion.Emit(b, doc, name, schema, resolveName)
		}
	case "object", "":
		b.WriteString("type ")
		b.WriteString(typeName)
		b.WriteString(" struct {\n")
		if schema.Base != nil {
			b.WriteString("\t")
			b.WriteString(gotype.Ref(*schema.Base, resolveName))
			b.WriteString("\n")
		}
		required := contractutil.RequiredSet(schema)
		for _, propertyName := range contractutil.OrderedProperties(schema) {
			property := schema.Properties[propertyName]
			fieldType := gotype.Ref(property.Schema, resolveName)
			optional := ""
			if _, ok := required[propertyName]; !ok {
				fieldType = "*" + fieldType
				optional = ",omitempty"
			}
			b.WriteString("\t")
			b.WriteString(fieldName(propertyName))
			b.WriteString(" ")
			b.WriteString(fieldType)
			b.WriteString(" `json:")
			b.WriteString(quotedGoString(propertyName + optional))
			b.WriteString(" yaml:")
			b.WriteString(quotedGoString(propertyName + optional))
			b.WriteString("`\n")
		}
		b.WriteString("}\n\n")
	case "array":
		elem := "any"
		if schema.Items != nil {
			elem = gotype.Ref(*schema.Items, resolveName)
		}
		b.WriteString("type ")
		b.WriteString(typeName)
		b.WriteString(" []")
		b.WriteString(elem)
		b.WriteString("\n\n")
	default:
		b.WriteString("type ")
		b.WriteString(typeName)
		b.WriteString(" ")
		b.WriteString(gotype.Ref(ir.SchemaRef{Type: schema.Type, Items: schema.Items}, resolveName))
		b.WriteString("\n\n")
		emitEnumConstants(b, typeName, schema.Enum)
	}
}

func dependencyNames(doc ir.Document, imports contractimport.Bindings) ([]string, []string) {
	return contractutil.DependencyNamesPartition(doc, func(name string, _ ir.Schema) bool {
		_, _, ok := imports.Schema(doc, name)
		return ok
	})
}

func emitImports(b *strings.Builder, values map[string]string) {
	if len(values) == 0 {
		return
	}
	paths := make([]string, 0, len(values))
	for path := range values {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	b.WriteString("import (\n")
	for _, path := range paths {
		if alias := values[path]; alias != "" {
			b.WriteString("\t" + alias + " ")
		} else {
			b.WriteString("\t")
		}
		b.WriteString(quotedGoString(path) + "\n")
	}
	b.WriteString(")\n\n")
}

func hasUnion(doc ir.Document, names []string) bool {
	for _, name := range names {
		if doc.Schemas[name].Type == "union" && (doc.Schemas[name].Discriminator != nil || hasScalarObjectUnion(doc.Schemas[name])) {
			return true
		}
	}
	return false
}

func hasScalarObjectUnion(schema ir.Schema) bool {
	if schema.Type != "union" || schema.Discriminator != nil {
		return false
	}
	hasScalar := false
	hasObject := false
	for _, variant := range schema.OneOf {
		if variant.Ref != "" {
			hasObject = true
			continue
		}
		switch strings.ToLower(strings.TrimSpace(variant.Type)) {
		case "boolean", "integer", "number", "string", "null":
			hasScalar = true
		}
	}
	return hasScalar && hasObject
}

func schemaRefGoType(ref ir.SchemaRef) string {
	return gotype.Ref(ref, exportedName)
}

func schemaGoType(schemaType string, items *ir.SchemaRef, format string) string {
	return gotype.Ref(ir.SchemaRef{Type: schemaType, Items: items, Format: format}, exportedName)
}

func emitEnumConstants(b *strings.Builder, typeName string, values []string) {
	if len(values) == 0 {
		return
	}
	b.WriteString("const (\n")
	for _, value := range values {
		b.WriteString("\t")
		b.WriteString(typeName)
		b.WriteString(exportedName(value))
		b.WriteString(" ")
		b.WriteString(typeName)
		b.WriteString(" = ")
		b.WriteString(quotedGoString(value))
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")
}

func exportedName(value string) string {
	parts := splitIdentifier(value)
	if len(parts) == 0 {
		return "Value"
	}
	for i := range parts {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

var initialisms = map[string]string{
	"api": "API", "html": "HTML", "http": "HTTP", "https": "HTTPS",
	"id": "ID", "ip": "IP", "json": "JSON", "ms": "MS", "nan": "NaN",
	"rpc": "RPC", "sql": "SQL", "sso": "SSO", "tcp": "TCP", "tls": "TLS",
	"ui": "UI", "uri": "URI", "url": "URL", "uuid": "UUID", "xml": "XML",
}

func fieldName(value string) string {
	parts := splitIdentifier(value)
	if len(parts) == 0 {
		return "Value"
	}
	for index, part := range parts {
		if initialism, ok := initialisms[strings.ToLower(part)]; ok {
			parts[index] = initialism
			continue
		}
		parts[index] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

func splitIdentifier(value string) []string {
	value = strings.TrimSpace(value)
	if value == "" {
		return nil
	}
	var words []string
	var current strings.Builder
	var prevLower bool
	for _, r := range value {
		if r == '-' || r == '_' || r == '.' || r == '/' || r == ' ' {
			if current.Len() > 0 {
				words = append(words, current.String())
				current.Reset()
			}
			prevLower = false
			continue
		}
		isUpper := 'A' <= r && r <= 'Z'
		if isUpper && prevLower && current.Len() > 0 {
			words = append(words, current.String())
			current.Reset()
		}
		current.WriteRune(r)
		prevLower = 'a' <= r && r <= 'z'
	}
	if current.Len() > 0 {
		words = append(words, current.String())
	}
	if len(words) == 0 {
		return nil
	}
	return words
}

func quotedGoString(value string) string {
	return `"` + strings.ReplaceAll(value, `"`, `\"`) + `"`
}
