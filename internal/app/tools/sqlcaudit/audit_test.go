func TestAuditFingerprintsResolvedConstants(t *testing.T) {
	body := `package postgres
import "context"
const (
	base = "SELECT "
	statement = base + "1"
)
func f(tx interface{ Exec(context.Context, string, ...any) any }) {
	tx.Exec(context.Background(), statement)
}
`
	root := writeFixture(t, map[string]string{
		"internal/example/postgres/repository.go": body,
	})
	result := audit(root)
	if len(result.Findings) != 1 || !result.Findings[0].Static {
		t.Fatalf("expected resolved constant to be static, got findings=%#v errors=%#v", result.Findings, result.Errors)
	}
	if len(result.Errors) == 0 || !strings.Contains(result.Errors[0].Error(), "unclassified PostgreSQL Exec") {
		t.Fatalf("expected resolved constant SQL to remain rejected, got %#v", result.Errors)
	}
	changed := strings.Replace(body, `statement = base + "1"`, `statement = base + "2"`, 1)
	if err := os.WriteFile(filepath.Join(root, "internal/example/postgres/repository.go"), []byte(changed), 0o644); err != nil {
		t.Fatal(err)
	}
	result = audit(root)
	if len(result.Errors) == 0 || !strings.Contains(result.Errors[0].Error(), "unclassified PostgreSQL Exec") {
		t.Fatalf("expected changed constant to remain rejected, got %#v", result.Errors)
	}
}

