func TestAuditExceptionInventoryLineIsExact(t *testing.T) {
	body := `package postgres
import "context"
func ApplySchema(tx interface{ Exec(context.Context, string, ...any) any }, query string) {
	tx.Exec(context.Background(), query)
}
`
	root := writeFixture(t, map[string]string{
		"internal/example/postgres/repository.go": body,
	})
	result := audit(root)
	if len(result.Findings) != 1 {
		t.Fatalf("expected one finding, got %#v", result.Findings)
	}
	finding := result.Findings[0]
	inventory := "entries:\n  - file: internal/example/postgres/repository.go\n    line: " + strconv.Itoa(finding.Line+1) + "\n    function: ApplySchema\n    method: Exec\n    fingerprint: " + finding.Fingerprint + "\n    class: schema-ddl\n    rationale: Test DDL boundary.\n    verification: Test coverage.\n"
	if err := os.WriteFile(filepath.Join(root, "internal/example/postgres/sqlc_exceptions.yaml"), []byte(inventory), 0o644); err != nil {
		t.Fatal(err)
	}
	result = audit(root)
	if len(result.Errors) < 2 {
		t.Fatalf("expected wrong-line inventory to be unclassified and stale, got %#v", result.Errors)
	}
}

