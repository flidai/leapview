func TestEvaluateRejectsEveryBudgetDimension(t *testing.T) {
	policy := testBudget()
	policy.Categories["go-production"] = categoryBudget{
		LineLimit: 3, MaxFilesOverLimit: 1, MaxExcessLines: 2, MaxLargestFile: 5,
	}
	policy.Suppressions["nolint"] = suppressionBudget{Marker: "//nolint", MaxOccurrences: 1}
	result := report{
		Categories: map[string]categoryResult{
			"go-production": {FilesOverLimit: 2, ExcessLines: 3, LargestFile: 6},
		},
		Suppressions: map[string]int{"nolint": 2},
	}
	problems := strings.Join(evaluate(policy, result), "\n")
	for _, want := range []string{"files over", "excess lines", "largest file", "nolint occurrences"} {
		if !strings.Contains(problems, want) {
			t.Fatalf("problems %q do not contain %q", problems, want)
		}
	}
}

func TestRatchetTightensButRequiresExplicitIncrease(t *testing.T) {
	policy := testBudget()
	policy.Categories["go-production"] = categoryBudget{
		LineLimit: 100, MaxFilesOverLimit: 4, MaxExcessLines: 80, MaxLargestFile: 240,
	}
	policy.Suppressions["nolint"] = suppressionBudget{Marker: "//nolint", MaxOccurrences: 3}
	result := report{
		Categories: map[string]categoryResult{
			"go-production": {FilesOverLimit: 3, ExcessLines: 60, LargestFile: 220},
		},
		Suppressions: map[string]int{"nolint": 2},
	}
	updated, increases := ratchet(policy, result, false)
	if len(increases) != 0 {
		t.Fatalf("unexpected increases: %v", increases)
	}
	if got := updated.Categories["go-production"]; got.MaxFilesOverLimit != 3 || got.MaxExcessLines != 60 || got.MaxLargestFile != 220 {
		t.Fatalf("tightened category = %#v", got)
	}
	if updated.Suppressions["nolint"].MaxOccurrences != 2 {
		t.Fatalf("tightened suppression = %#v", updated.Suppressions["nolint"])
	}

	result.Categories["go-production"] = categoryResult{FilesOverLimit: 5, ExcessLines: 100, LargestFile: 260}
	result.Suppressions["nolint"] = 4
	unchanged, increases := ratchet(policy, result, false)
	if !reflect.DeepEqual(increases, []string{"go-production", "nolint"}) {
		t.Fatalf("increases = %v", increases)
	}
	if !reflect.DeepEqual(unchanged, policy) {
		t.Fatalf("policy changed without approval: %#v", unchanged)
	}
}

