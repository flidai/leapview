func testBudget() budget {
	return budget{
		Version: currentVersion,
		Categories: map[string]categoryBudget{
			"go-production":         {LineLimit: 3},
			"go-test":               {LineLimit: 3},
			"typescript-production": {LineLimit: 3},
			"typescript-test":       {LineLimit: 3},
		},
		Suppressions: map[string]suppressionBudget{
			"nolint":    {Marker: "/" + "/nolint"},
			"nosec":     {Marker: "#" + "nosec"},
			"ts-ignore": {Marker: "@" + "ts-ignore"},
		},
	}
}
func TestGeneratedSourceRequiresAHeaderComment(t *testing.T) {
	generatedNotice := "Code " + "generated by fixture. DO " + "NOT EDIT."
	if !generatedSource("internal/example/generated.go", []byte("// "+generatedNotice+"\npackage example\n")) {
		t.Fatal("leading generated notice was not detected")
	}
	authoredFixture := []byte("package example\nconst notice = `" + generatedNotice + "`\n")
	if generatedSource("internal/example/service_test.go", authoredFixture) {
		t.Fatal("generated notice inside an authored string excluded the whole file")
	}
}

func TestCommentMarkerCountIgnoresStringLiterals(t *testing.T) {
	marker := "/" + "/nolint"
	body := []byte(strings.Join([]string{
		"package example",
		"const documented = `" + marker + "`",
		"func example() {} " + marker + ":funlen",
		"/* reviewed " + marker + ":gocyclo */",
	}, "\n"))
	if got := commentMarkerCount(body, marker); got != 2 {
		t.Fatalf("comment marker count = %d, want 2", got)
	}
}
