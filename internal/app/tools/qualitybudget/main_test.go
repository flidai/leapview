func TestAnalyzeMeasuresHotspotAndSuppressionDebt(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"internal/example/service.go": strings.Join([]string{
			"package example", "func first() {}", "func second() {}", "/" + "/nolint:funlen", "",
		}, "\n"),
		"internal/example/service_test.go": "package example\n// " + "#" + "nosec test fixture\n",
		"web/example.ts":                   "// " + "@" + "ts-ignore reviewed fixture\nexport const value = 1\n",
		"web/generated/contracts.ts":       "// " + "@" + "ts-ignore generated\nexport const generated = true\n",
		"internal/example/generated.go":    "// Code generated by fixture. DO NOT EDIT.\npackage example\n/" + "/nolint\n",
	}
	paths := make([]string, 0, len(files))
	for path, body := range files {
		absolute := filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(absolute), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(absolute, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		paths = append(paths, path)
	}
	policy := testBudget()
	result, err := analyze(root, paths, policy)
	if err != nil {
		t.Fatal(err)
	}
	production := result.Categories["go-production"]
	if production.Files != 1 || production.FilesOverLimit != 1 || production.ExcessLines != 1 || production.LargestFile != 4 {
		t.Fatalf("go production measurement = %#v", production)
	}
	if got := result.Suppressions; !reflect.DeepEqual(got, map[string]int{"nolint": 1, "nosec": 1, "ts-ignore": 1}) {
		t.Fatalf("suppressions = %#v", got)
	}
}

